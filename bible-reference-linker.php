 * Scan $text for "<Book Name> <chapter>[:<verse>]" references and wrap each
 * recognized one in a link to the WordOfGod.in online Bible reader. Returns
 * HTML-safe markup (the caller should NOT also run htmlspecialchars on the
 * result). Unmatched text is left as plain (escaped) text.
 */
function linkBibleReferences($text, $language) {
    if ($text === null || $text === '') {
        return '';
    }

    $candidates = getBibleReferenceCandidates($language);
    if (empty($candidates)) {
        return htmlspecialchars($text);
    }

    $nameToBook = [];
    $patternParts = [];
    foreach ($candidates as $candidate) {
        $nameToBook[$candidate['name']] = $candidate['book'];
        $patternParts[] = preg_quote($candidate['name'], '/');
    }

    $pattern = '/(' . implode('|', $patternParts) . ')\s*(\d{1,3})(?:\s*[:.]\s*(\d{1,3}))?/u';

    if (!preg_match_all($pattern, $text, $matches, PREG_OFFSET_CAPTURE | PREG_SET_ORDER)) {
        return htmlspecialchars($text);
    }

    $output = '';
    $cursor = 0;

    foreach ($matches as $match) {
        $matchText = $match[0][0];
        $matchStart = $match[0][1];
        $bookName = $match[1][0];
        $chapter = (int) $match[2][0];
        $verse = isset($match[3][0]) && $match[3][0] !== '' ? (int) $match[3][0] : null;
        $bookNo = $nameToBook[$bookName] ?? null;

        // Text between the previous match and this one
        $output .= htmlspecialchars(substr($text, $cursor, $matchStart - $cursor));

        if ($bookNo !== null && $chapter > 0) {
            $url = 'https://wordofgod.in/bibles/?book=' . $bookNo . '&chapter=' . $chapter;
            if ($verse !== null && $verse > 0) {
                $url .= '&verse=' . $verse;
            }
            $url .= '&lang=' . urlencode($language);

            $output .= '<a href="' . htmlspecialchars($url) . '" target="_blank" rel="noopener" class="bible-ref-link">'
                . htmlspecialchars($matchText) . '</a>';
        } else {
            $output .= htmlspecialchars($matchText);
        }

        $cursor = $matchStart + strlen($matchText);
    }

    // Remaining text after the last match
    $output .= htmlspecialchars(substr($text, $cursor));

    return $output;
}
