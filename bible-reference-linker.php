/**
 * Build (once per request) a [bookNumber, name] candidate list sorted by
 * name length descending, so longer/more specific names (e.g. "1 John")
 * are tried before shorter ones (e.g. "John") at the same text position.
 */
function getBibleReferenceCandidates($language) {
    static $cache = [];
    if (isset($cache[$language])) {
        return $cache[$language];
    }

    $namesByLanguage = $GLOBALS['bibleBookNames'];
    $names = $namesByLanguage[$language] ?? $namesByLanguage['English'];

    $candidates = [];
    foreach ($names as $bookNo => $variants) {
        foreach ($variants as $variant) {
            $candidates[] = ['book' => $bookNo, 'name' => $variant];
        }
    }

    usort($candidates, function ($a, $b) {
        return mb_strlen($b['name']) <=> mb_strlen($a['name']);
    });

    $cache[$language] = $candidates;
    return $candidates;
}

/**
 * Scan $text for "<Book Name> <chapter>[:<verse>]" references and wrap each
 * recognized one in a link to the WordOfGod.in online Bible reader. Returns
 * HTML-safe markup (the caller should NOT also run htmlspecialchars on the
 * result). Unmatched text is left as plain (escaped) text.
 */
function linkBibleReferences($text, $language) {
    if ($text === null || $text === '') {
        return '';
    }

    $candidates = getBibleReferenceCandidates($language);
    if (empty($candidates)) {
        return htmlspecialchars($text);
    }

    $nameToBook = [];
    $patternParts = [];
    foreach ($candidates as $candidate) {
        $nameToBook[$candidate['name']] = $candidate['book'];
        $patternParts[] = preg_quote($candidate['name'], '/');
    }

    $pattern = '/(?<![\p{L}\p{N}])(' . implode('|', $patternParts) . ')\s*(\d{1,3})(?:\s*[:.]\s*(\d{1,3}))?/u';

    if (!preg_match_all($pattern, $text, $matches, PREG_OFFSET_CAPTURE | PREG_SET_ORDER)) {
        return htmlspecialchars($text);
    }

    $output = '';
    $cursor = 0;

    foreach ($matches as $match) {
        $matchText = $match[0][0];
        $matchStart = $match[0][1];
        $bookName = $match[1][0];
        $chapter = (int) $match[2][0];
        $verse = isset($match[3][0]) && $match[3][0] !== '' ? (int) $match[3][0] : null;
        $bookNo = $nameToBook[$bookName] ?? null;

        // Text between the previous match and this one
        $output .= htmlspecialchars(substr($text, $cursor, $matchStart - $cursor));

        if ($bookNo !== null && $chapter > 0) {
            $url = 'https://wordofgod.in/bibles/?book=' . $bookNo . '&chapter=' . $chapter;
            if ($verse !== null && $verse > 0) {
                $url .= '&verse=' . $verse;
            }
            $url .= '&lang=' . urlencode($language);

            $output .= '<a href="' . htmlspecialchars($url) . '" target="_blank" rel="noopener" class="bible-ref-link">'
                . htmlspecialchars($matchText) . '</a>';
        } else {
            $output .= htmlspecialchars($matchText);
        }

        $cursor = $matchStart + strlen($matchText);
    }

    // Remaining text after the last match
    $output .= htmlspecialchars(substr($text, $cursor));

    return $output;
}

/**
 * Formats a structured key_verse value (e.g. "1_1:1", "46_12:12-26", or
 * multiple references joined with ";") into human-readable, linked Bible
 * references in the given language, e.g. "Genesis 1:1". Used anywhere a
 * meditation's key_verse should be shown instead of/alongside its date.
 * Returns '' if $keyVerse is empty or unparseable.
 */
function formatKeyVerseLink($keyVerse, $language) {
    if (empty($keyVerse)) {
        return '';
    }

    $namesByLanguage = $GLOBALS['bibleBookNames'];
    $names = $namesByLanguage[$language] ?? $namesByLanguage['English'];

    $parts = [];
    foreach (explode(';', $keyVerse) as $segment) {
        $segment = trim($segment);
        if (!preg_match('/^(\d+)_(\d+)(?::(\d+))?/', $segment, $m)) {
            continue;
        }

        $bookNo = (int) $m[1];
        $chapter = (int) $m[2];
        $verse = isset($m[3]) && $m[3] !== '' ? (int) $m[3] : null;

        $bookName = $names[$bookNo][0] ?? $namesByLanguage['English'][$bookNo][0] ?? null;
        if ($bookName === null || $chapter <= 0) {
            continue;
        }

        $display = $bookName . ' ' . $chapter . ($verse !== null ? ':' . $verse : '');

        $url = 'https://wordofgod.in/bibles/?book=' . $bookNo . '&chapter=' . $chapter;
        if ($verse !== null && $verse > 0) {
            $url .= '&verse=' . $verse;
        }
        $url .= '&lang=' . urlencode($language);

        $parts[] = '<a href="' . htmlspecialchars($url) . '" target="_blank" rel="noopener" class="bible-ref-link">'
            . htmlspecialchars($display) . '</a>';
    }

    return implode('; ', $parts);
}
